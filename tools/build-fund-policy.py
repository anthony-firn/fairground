"""Compile dependency-free Rust policy and embed its small Wasm module for Node and browsers."""
from pathlib import Path
import hashlib
import subprocess

root = Path(__file__).resolve().parents[1]
subprocess.run(['cargo', '+1.91.1', 'build', '--manifest-path', str(root/'crates/fund-policy/Cargo.toml'),
                '--locked', '--release', '--target', 'wasm32-unknown-unknown'], check=True)
wasm = (root/'crates/fund-policy/target/wasm32-unknown-unknown/release/fairground_fund_policy.wasm').read_bytes()
out = root/'src/generated/fundPolicyWasm.ts'
out.parent.mkdir(exist_ok=True)
out.write_text('// Generated by tools/build-fund-policy.py; do not edit.\n'
               f'// SHA-256: {hashlib.sha256(wasm).hexdigest()}\n'
               'export const fundPolicyWasm = new Uint8Array(['+','.join(map(str,wasm))+']);\n')
print(f'Embedded {len(wasm)} bytes; SHA-256 {hashlib.sha256(wasm).hexdigest()}')
